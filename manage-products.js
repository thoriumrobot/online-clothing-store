#!/usr/bin/env node
/* =========================================================
   SAAK catalog manager
   Add and remove store items from the command line.

   Usage (run from the project root):
     node manage-products.js list
     node manage-products.js add "<name>" <price> <category> [image] [badge]
     node manage-products.js remove <id | exact name>

   Examples:
     node manage-products.js add "Wool Beanie" 22.00 accessories images/cap.svg "New"
     node manage-products.js add "Linen Shirt" 45 tops
     node manage-products.js remove p7
     node manage-products.js remove "Canvas Tote"

   Categories with size selectors: tops, bottoms, outerwear.
   Anything else (e.g. accessories) is sold without sizes.
   ========================================================= */
const fs = require('fs');
const path = require('path');

const FILE = path.join(__dirname, 'scripts', 'products.js');
const CATEGORIES = ['tops', 'bottoms', 'outerwear', 'accessories'];
const DEFAULT_IMG = 'images/tee.svg';

function load() {
  delete require.cache[require.resolve(FILE)];
  return require(FILE);
}

function save(products) {
  const rows = products.map((p) => {
    const parts = [
      `"id": ${JSON.stringify(p.id)}`,
      `"name": ${JSON.stringify(p.name)}`,
      `"price": ${p.price.toFixed(2)}`,
      `"category": ${JSON.stringify(p.category)}`,
      `"img": ${JSON.stringify(p.img)}`,
    ];
    if (p.badge) parts.push(`"badge": ${JSON.stringify(p.badge)}`);
    return `  { ${parts.join(', ')} }`;
  });

  const content = `/* =========================================================
   SAAK — product catalog (data only)
   Edit by hand, or use the CLI from the project root:
     node manage-products.js list
     node manage-products.js add "Wool Beanie" 22.00 accessories images/cap.svg "New"
     node manage-products.js remove p7
   This file is regenerated by the CLI — keep the format.
   ========================================================= */
(function () {
const PRODUCTS = [
${rows.join(',\n')}
];

/* Works both in the browser and in Node (for the CLI and tests) */
if (typeof module !== 'undefined') module.exports = PRODUCTS;
if (typeof window !== 'undefined') window.SAAK_PRODUCTS = PRODUCTS;
})();
`;
  fs.writeFileSync(FILE, content);
}

function nextId(products) {
  const max = products.reduce((m, p) => {
    const n = /^p(\d+)$/.exec(p.id);
    return n ? Math.max(m, parseInt(n[1], 10)) : m;
  }, 0);
  return 'p' + (max + 1);
}

function list(products) {
  if (products.length === 0) { console.log('Catalog is empty.'); return; }
  const w = Math.max(...products.map((p) => p.name.length));
  products.forEach((p) => {
    console.log(
      `${p.id.padEnd(4)} ${p.name.padEnd(w + 2)} ₱${p.price.toLocaleString('en-PH', { minimumFractionDigits: 2 }).padStart(9)}  ` +
      `${p.category.padEnd(12)} ${p.img}${p.badge ? '  [' + p.badge + ']' : ''}`
    );
  });
  console.log(`\n${products.length} item(s) in catalog.`);
}

function add(products, args) {
  const [name, priceRaw, category, img, badge] = args;
  if (!name || !priceRaw || !category) {
    fail('Usage: node manage-products.js add "<name>" <price> <category> [image] [badge]');
  }
  const price = parseFloat(priceRaw);
  if (!isFinite(price) || price <= 0) fail(`"${priceRaw}" is not a valid price.`);
  if (!CATEGORIES.includes(category)) {
    fail(`Unknown category "${category}". Use one of: ${CATEGORIES.join(', ')}.`);
  }
  if (products.some((p) => p.name.toLowerCase() === name.toLowerCase())) {
    fail(`An item named "${name}" already exists. Remove it first or pick another name.`);
  }
  const image = img || DEFAULT_IMG;
  const imagePath = path.join(__dirname, image);
  if (!fs.existsSync(imagePath)) {
    console.warn(`  ! Warning: image "${image}" not found in the project — the card will show a broken image until you add it.`);
  }
  const item = { id: nextId(products), name, price, category, img: image };
  if (badge) item.badge = badge;
  products.push(item);
  save(products);
  console.log(`Added ${item.id}: ${item.name} — ₱${price.toLocaleString('en-PH', { minimumFractionDigits: 2 })} (${category})`);
}

function remove(products, args) {
  const key = args[0];
  if (!key) fail('Usage: node manage-products.js remove <id | exact name>');
  const idx = products.findIndex(
    (p) => p.id === key || p.name.toLowerCase() === key.toLowerCase()
  );
  if (idx === -1) fail(`No item with id or name "${key}". Run "list" to see the catalog.`);
  const [gone] = products.splice(idx, 1);
  save(products);
  console.log(`Removed ${gone.id}: ${gone.name}`);
}

function fail(msg) { console.error(msg); process.exit(1); }

const [, , cmd, ...args] = process.argv;
const products = load();

if (cmd === 'list') list(products);
else if (cmd === 'add') add(products, args);
else if (cmd === 'remove') remove(products, args);
else {
  console.log('SAAK catalog manager\n');
  console.log('  node manage-products.js list');
  console.log('  node manage-products.js add "<name>" <price> <category> [image] [badge]');
  console.log('  node manage-products.js remove <id | exact name>\n');
  console.log(`Categories: ${CATEGORIES.join(', ')}`);
  process.exit(cmd ? 1 : 0);
}
